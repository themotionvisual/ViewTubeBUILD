export const resolveAnalyticsVisualIcon = (iconKey: string | undefined): LucideIcon => {
  if (!iconKey) return BarChart3
  return VISUAL_ICON_MAP[iconKey] ?? BarChart3
}

export const AnalyticsVisualIcon: React.FC<{
  iconKey?: string
  size?: number
  strokeWidth?: number
  className?: string
}> = ({ iconKey, size = 58, strokeWidth = 3, className }) => {
  const Icon = resolveAnalyticsVisualIcon(iconKey)
  return <Icon size={size} strokeWidth={strokeWidth} className={className} />
}
